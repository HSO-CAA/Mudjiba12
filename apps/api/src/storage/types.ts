export interface PutOptions {
  contentType: string;
  /** Remove the local source file after a successful put (rename when possible). */
  move?: boolean;
}

export interface LocalFileHandle {
  /** Absolute local path that can be read (e.g. by ffmpeg). */
  path: string;
  /** Removes temporary copies (no-op for the local driver). */
  cleanup(): Promise<void>;
}

/** Minimal logger (pino-compatible) used by storage drivers. */
export interface StorageLog {
  info(obj: object, msg?: string): void;
  warn(obj: object, msg?: string): void;
  error(obj: object, msg?: string): void;
}

/**
 * Where media files live. Keys are always generated by the server
 * (`images/…`, `videos/<id>/…`) and validated by `assertSafeKey`.
 */
export interface StorageDriver {
  readonly kind: 'local' | 's3' | 'supabase';
  /** Origin to allow in the CSP (`img-src`/`media-src`), or null when everything is served from `/media`. */
  readonly publicOrigin: string | null;
  /**
   * Directory served at `/media/*` because some objects live on this server's disk (the local driver, or
   * video sources staged locally next to a remote driver); null when nothing is served from disk.
   */
  readonly localMediaDir: string | null;
  /**
   * Optional start-up hook (e.g. create/publish the Supabase bucket). Must not throw: problems are logged with
   * an actionable message so the site still starts.
   */
  init?(log: StorageLog): Promise<void>;
  /** Ready-to-use URL: `/media/<key>` (local), `${S3_PUBLIC_URL}/<key>` or the Supabase public object URL. */
  url(key: string): string;
  putFile(key: string, filePath: string, options: PutOptions): Promise<void>;
  delete(key: string): Promise<void>;
  /** Deletes every object whose key starts with `prefix` (must end with "/"). */
  deletePrefix(prefix: string): Promise<void>;
  exists(key: string): Promise<boolean>;
  /** Gives a local readable copy of an object, downloading it when needed into `tmpDir`. */
  getLocalFile(key: string, tmpDir: string): Promise<LocalFileHandle>;
  /** Total bytes stored, when cheaply measurable; null otherwise. */
  usageBytes(): Promise<number | null>;
}

const KEY_RE = /^(?:images|videos)\/(?:[A-Za-z0-9_-]+\/)*[A-Za-z0-9_-]+(?:\.[A-Za-z0-9]{1,8})?$/;
const PREFIX_RE = /^(?:images|videos)\/(?:[A-Za-z0-9_-]+\/)+$/;

/** Throws if `key` is not a server-shaped storage key (blocks traversal, absolute paths, dotfiles). */
export function assertSafeKey(key: string): void {
  if (key.length > 300 || !KEY_RE.test(key)) throw new Error(`Unsafe storage key: ${JSON.stringify(key)}`);
}

export function assertSafePrefix(prefix: string): void {
  if (prefix.length > 300 || !PREFIX_RE.test(prefix)) throw new Error(`Unsafe storage prefix: ${JSON.stringify(prefix)}`);
}

/** The remote store rejected an object because it exceeds its per-file size limit (e.g. Supabase Free: 50 MB). */
export class StorageObjectTooLargeError extends Error {
  constructor(
    readonly provider: string,
    readonly key: string,
  ) {
    super(`${provider}: object "${key}" exceeds the maximum allowed size`);
    this.name = 'StorageObjectTooLargeError';
  }
}

/** The remote store rejected our credentials (wrong / anon key, other project, paused project…). */
export class StorageAuthError extends Error {
  constructor(
    readonly provider: string,
    readonly status: number,
    detail: string,
  ) {
    super(`${provider}: request rejected (HTTP ${status}${detail ? `: ${detail}` : ''}) — check the service key`);
    this.name = 'StorageAuthError';
  }
}

/** Any other failed request to a remote store (after retries). Messages never contain credentials. */
export class StorageRequestError extends Error {
  constructor(
    readonly provider: string,
    readonly status: number | null,
    message: string,
  ) {
    super(`${provider}: ${message}`);
    this.name = 'StorageRequestError';
  }
}

/** `videos/<id>/source.<ext>` — the original upload of a video. */
const SOURCE_KEY_RE = /^videos\/[A-Za-z0-9_-]+\/source\.[A-Za-z0-9]{1,8}$/;
export const isVideoSourceKey = (key: string): boolean => SOURCE_KEY_RE.test(key);

/** Long-lived caching is safe: every stored object has a unique key. */
export const IMMUTABLE_CACHE_CONTROL = 'public, max-age=31536000, immutable';
